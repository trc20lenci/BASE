import 'dart:io';
import '../../../editor/domain/entities/editor_timeline_entity.dart';
import '../entities/export_settings.dart';

/// Абстракция движка рендера итогового MP4 из таймлайна проекта.
///
/// ВАЖНО (архитектурное решение): рендер видео на устройстве — это
/// единственная часть MVP, для которой мы сознательно НЕ фиксируем
/// конкретную нативную реализацию прямо сейчас. Причина: наиболее
/// очевидный кандидат — `ffmpeg_kit_flutter` — был официально свёрнут
/// автором (репозиторий arthenica/ffmpeg-kit заброшен), поэтому
/// зашивать в архитектуру именно его — плохое инженерное решение на
/// старте нового проекта.
///
/// Вместо этого мы фиксируем контракт (вход: таймлайн + настройки
/// рендера, выход: локальный MP4-файл с колбэком прогресса) и подключаем
/// конкретный движок отдельным PR, когда будет выбрана актуальная на
/// тот момент библиотека (форк ffmpeg-kit, нативный MediaCodec-пайплайн
/// или сторонний SDK). Это не влияет на остальной MVP — UI экспорта
/// полностью готов и просто вызывает этот контракт.
abstract class VideoExportEngine {
  /// Рендерит таймлайн в единый MP4-файл согласно [settings].
  /// [onProgress] вызывается с значением 0..1 по ходу рендера.
  Future<File> render({
    required EditorTimelineEntity timeline,
    required ExportSettings settings,
    required void Function(double progress) onProgress,
  });
}
